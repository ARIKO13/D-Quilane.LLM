"""
Minimal CPU inference for D'QUILANE containers (chimera_8b_effective).

These files are GGUF-shaped but use a custom architecture, so llama.cpp and
ollama will refuse them. Load them here:

    python infer_dquilane.py --model D-QUILANE-trainer.gguf --prompt "apa itu fotosintesis"
    python infer_dquilane.py --model D-QUILANE-trainer.gguf            # interactive

Two paths:
  1. AION engram hit  → the answer is read from the stored prompt→answer table
     (this is retrieval, not generation).
  2. AION miss        → the 215K-param char model continues the text. Expect
     gibberish-ish character statistics, not factual answers.
"""
import argparse
import json
import os
import sys

import torch

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from chimera_model import load_from_gguf, normalize_aion_key


def aion_lookup(prompt, engram):
    """Exact key first, then the longest key that prefixes/suffixes the prompt."""
    key = normalize_aion_key(prompt)
    if key in engram:
        return engram[key], key
    best = None
    for k, v in engram.items():
        if not k:
            continue
        if key.startswith(k) or k.startswith(key):
            if best is None or len(k) > len(best[0]):
                best = (k, v)
    return (best[1], best[0]) if best else (None, None)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--model', default=os.path.join(HERE, 'D-QUILANE-trainer.gguf'))
    ap.add_argument('--prompt', default=None)
    ap.add_argument('--max-new', type=int, default=120)
    ap.add_argument('--temp', type=float, default=0.7)
    ap.add_argument('--top-k', type=int, default=10)
    ap.add_argument('--entrocut', type=float, default=0.0,
                    help='stop when max next-char probability > this (0 = off)')
    ap.add_argument('--no-aion', action='store_true',
                    help='skip the retrieval table and always sample from the network')
    args = ap.parse_args()

    model, meta = load_from_gguf(args.model)
    stoi = json.loads(meta.get('tokenizer_stoi', '{}'))
    itos = {int(k): v for k, v in json.loads(meta.get('tokenizer_itos', '{}')).items()}
    eos_id = int(meta.get('eos_id', -1))
    engram = json.loads(meta.get('aion_engram', '{}'))
    pad_id = stoi.get('<pad>')

    print(f"[load] {os.path.basename(args.model)}: "
          f"{model.count_params():,} params, vocab {model.cfg['vocab_size']}, "
          f"blocks {model.cfg['n_blocks']}x{model.cfg['n_repeat']}, "
          f"AION pairs {len(engram):,}")

    def encode(text):
        return [stoi[c] for c in text if c in stoi]

    def decode(ids):
        out = []
        for i in ids:
            i = int(i)
            if i == eos_id or i == pad_id:
                break
            out.append(itos.get(i, ''))
        return ''.join(out)

    def answer(prompt):
        if engram and not args.no_aion:
            hit, key = aion_lookup(prompt, engram)
            if hit is not None:
                print(f"[aion] retrieved (key={key!r}) - not generated by the network")
                return hit
        ids = encode(prompt) or encode('a')
        if len(ids) >= model.cfg['max_seq']:
            ids = ids[-(model.cfg['max_seq'] - args.max_new - 1):]
        gen = model.generate(torch.tensor([ids], dtype=torch.long),
                             max_new=args.max_new, temp=args.temp,
                             top_k=args.top_k,
                             stop_id=eos_id if eos_id >= 0 else None,
                             entrocut=args.entrocut)
        print("[net] sampled from the 215K-param char model")
        return decode(gen[0, len(ids):].tolist())

    if args.prompt:
        out = answer(args.prompt)
        print(out.strip() or '(empty)')
        return

    print("Interactive. Ctrl+C to quit.")
    while True:
        try:
            prompt = input('\n> ').strip()
        except (EOFError, KeyboardInterrupt):
            print()
            break
        if prompt:
            print(answer(prompt).strip())


if __name__ == '__main__':
    main()
